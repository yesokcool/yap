#!/usr/bin/env node
/*
 * Stamps the web client's build id into both halves of Yap, so open pages
 * can tell when a deploy changed them (see PROTOCOL.md › Updates):
 *   web/js/build.js   — what this copy of the page is
 *   worker/build.ts   — what the server is currently serving
 * `style` hashes the stylesheet (a CSS-only change is swapped in place);
 * `app` hashes everything else the page loads (that needs a reload).
 * Both files are generated, never committed (.gitignore): npm install,
 * `npm run dev`, `dev:test`, `check` and `deploy` all run this first. Writes
 * only on change. --quiet: say nothing.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT } from './lib.mjs';

const web = join(ROOT, 'web');
const STYLES = ['style.css']; // swapped in place on update
const SKIP = new Set(['js/build.js', ...STYLES, '_headers']);
const SKIP_DIRS = new Set(['downloads']);

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const path = join(dir, e.name);
    if (e.name.startsWith('.')) return [];
    if (e.isDirectory()) return SKIP_DIRS.has(relative(web, path)) ? [] : files(path);
    return [path];
  });
}

const hash = (h) => h.digest('hex').slice(0, 12);
const app = createHash('sha256');
for (const path of files(web).map((p) => relative(web, p)).filter((p) => !SKIP.has(p)).sort()) {
  app.update(`${path}\0`);
  app.update(readFileSync(join(web, path)));
  app.update('\0');
}
const style = createHash('sha256');
for (const name of STYLES) style.update(readFileSync(join(web, name)));
const build = { app: hash(app), style: hash(style) };
const json = JSON.stringify(build);

const write = (path, text) => {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
  writeFileSync(path, text);
  return true;
};
const changed = [
  write(join(web, 'js/build.js'), `// Generated by tools/stamp.mjs. Which build of the web client this is.\nexport const BUILD = ${json};\n`),
  write(join(ROOT, 'worker/build.ts'), `// Generated by tools/stamp.mjs. The web client build being served.\nexport const BUILD = ${json};\n`),
].some(Boolean);
if (!process.argv.includes('--quiet')) console.log(`build ${build.app} · style ${build.style}${changed ? '' : ' (unchanged)'}`);
